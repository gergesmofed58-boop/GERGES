export function convertToDisplayCurrency(
  amount: number,
  fromCurrency: MarketAsset['currency'],
  toCurrency: 'EGP' | 'USD' | 'SAR',
  fx: FxRates
): number {
  let usd = amount;
  switch (fromCurrency) {
    case 'USD':
      usd = amount;
      break;
    case 'EGP':
      usd = amount / fx.USD_EGP;
      break;
    case 'SAR':
      usd = amount / fx.USD_SAR;
      break;
    case 'AED':
      usd = amount / fx.USD_AED;
      break;
    case 'EUR':
      usd = amount / fx.USD_EUR;
      break;
    case 'JPY':
      usd = amount / fx.USD_JPY;
      break;
    case 'HKD':
      usd = amount / fx.USD_HKD;
      break;
  }

  if (toCurrency === 'USD') return usd;
  if (toCurrency === 'EGP') return usd * fx.USD_EGP;
  return usd * fx.USD_SAR;
}
