export function evaluateExchangeStatus(clock: ExchangeClockInfo, now: Date) {
  const utcMs = now.getTime() + now.getTimezoneOffset() * 60000;
  const local = new Date(utcMs + clock.timezoneOffsetHours * 3600000);
  const day = local.getDay();
  const mins = local.getHours() * 60 + local.getMinutes();
  const openMins = clock.openHour * 60 + clock.openMin;
  const closeMins = clock.closeHour * 60 + clock.closeMin;
  const isTradingDay = clock.tradingDays.includes(day);
  const isOpen = isTradingDay && mins >= openMins && mins < closeMins;

  const hh = String(local.getHours()).padStart(2, '0');
  const mm = String(local.getMinutes()).padStart(2, '0');

  let remainingMins = 0;
  if (isOpen) {
    remainingMins = closeMins - mins;
  } else if (isTradingDay && mins < openMins) {
    remainingMins = openMins - mins;
  }

  return {
    isOpen,
    localTime: `${hh}:${mm}`,
    remainingHours: Math.floor(remainingMins / 60),
    remainingMins: remainingMins % 60,
    opensTodaySoon: isTradingDay && mins < openMins,
  };
}

