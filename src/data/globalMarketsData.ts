function buildHistory(
  basePrice: number,
  currentPrice: number,
  volatility: number,
  avgVol: number,
  seed: number
): PricePoint[] {
  const points: PricePoint[] = [];
  const totalDays = 30;
  let running = basePrice;
  const drift = (currentPrice - basePrice) / totalDays;

  for (let i = totalDays - 1; i >= 0; i--) {
    const dt = new Date();
    dt.setDate(dt.getDate() - i);
    const wave = Math.sin((totalDays - i + seed) * 0.65) * volatility;
    const micro = Math.cos((totalDays - i) * 1.4 + seed) * (volatility * 0.45);
    if (i === 0) {
      running = currentPrice;
    } else {
      running = Math.max(0.5, running + drift + wave * 0.22 + micro * 0.15);
    }
    const volMultiplier = 0.72 + Math.abs(Math.sin(i * 0.9 + seed)) * 0.75;
    points.push({
      date: `${dt.getMonth() + 1}/${dt.getDate()}`,
      price: Number(running.toFixed(2)),
      volume: Math.round(avgVol * volMultiplier),
    });
  }
  return points;
}

